REAL_SPELLINGS = [
    "специальный инструмент", "концертмейстерский класс", "ансамблевое исполнительство", "дополнительный инструмент",
    "камерный ансамбль", "чтение с листа и транспозиция", "учебная практика по пед.работе", "концертмейстерская подготовка",
    "концертмейстерское искусство", "ансамбль", "изучение репертуара дмш", "изучение концертного репертуара",
    "основы импровизации и аранжировки", "фортепианный дуэт", "техническая подготовка", "концертмейский класс",
    "исполнительское искусство", "педагогическая практика", "практические основы работы с оперными клавирами",
    "исполнительство на старинных клавишных инструментах", "педагогический репертуар", "изучение оперных клавиров",
    "совершенствование конц.навыков", "учебная практика по пед работе", "исполнительство на органе",
    "чтение с листа и транспонирование", "изучение конц.репертуара", "совершенствование исполнительского искусства",
    "совершенствование исполнительских навыков", "фортепианнный дуэт", "основы имровизации и аранжировки",
    "концертмейсерская подготовка", "чтен.с листа и тр", "концертместерская подготовка",
]


def test_every_real_spelling_is_recognised():
    unknown = [s for s in REAL_SPELLINGS if subjects.find(s) is None]
    assert unknown == []


def test_typos_and_variants_map_to_the_same_subject():
    assert subjects.find("Концертмейский класс").name == "Концертмейстерский класс"
    assert subjects.find("конц.класс").name == "Концертмейстерский класс"
    assert subjects.find("ФОРТЕПИАННЫЙ  дуэт").name == "Фортепианный дуэт"
    assert subjects.find("Ансамбль").name == "Ансамблевое исполнительство"


def test_different_subjects_are_not_confused():
    """Похожие по написанию, но разные предметы (подготовка / искусство) не склеиваются."""
    assert subjects.find("концертмейстерская подготовка").name != subjects.find("концертмейстерское искусство").name
    assert subjects.find("специальный инструмент").name != subjects.find("дополнительный инструмент").name


def test_short_names_and_unknown_subject_left_as_is():
    assert subjects.short("специальный инструмент") == "спец."
    assert subjects.short("Концертмейский класс") == "конц. класс"
    assert subjects.short("История музыки") == "История музыки"      # не из словаря — не теряем
    assert subjects.short(None) == "" and subjects.short("  ") == ""
