_FUZZY_MIN = 0.9


def normalize(raw: str | None) -> str:
    s = (raw or "").casefold().replace("ё", "е")
    s = re.sub(r"[.,;:()\-–]", " ", s)
    return re.sub(r"\s+", " ", s).strip()


_INDEX: dict[str, Subject] = {normalize(a): s for s in SUBJECTS for a in (s.name, *s.aliases)}


def find(raw: str | None) -> Subject | None:
    """Предмет из словаря или None, если не опознан."""
    key = normalize(raw)
    if not key:
        return None
    if key in _INDEX:
        return _INDEX[key]
    best, best_ratio = None, 0.0
    for alias, subject in _INDEX.items():
        r = difflib.SequenceMatcher(None, key, alias).ratio()
        if r > best_ratio:
            best, best_ratio = subject, r
    return best if best_ratio >= _FUZZY_MIN else None


def short(raw: str | None) -> str:
    """Короткая запись предмета для раскладки; незнакомый предмет возвращается как написан."""
    if not raw:
        return ""
    subject = find(raw)
    return subject.short if subject else raw.strip()
