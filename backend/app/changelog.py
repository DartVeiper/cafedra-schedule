def entries_for_display() -> list[dict]:
    """Записи новее → старее, с признаками installed (текущая версия) и
    unreleased (новее установленной — работа в процессе)."""
    current = _parse_version(APP_VERSION)
    out = []
    for e in sorted(CHANGELOG, key=lambda e: _parse_version(e["version"]), reverse=True):
        v = _parse_version(e["version"])
        out.append({**e, "installed": v == current, "unreleased": v > current})
    return out


_RELEASE_FOOTER = """Если у вас установлена версия 0.3.0 или новее — проще всего обновиться прямо из приложения: на главной странице появится баннер «Доступна новая версия» с кнопкой «Скачать и установить», ничего скачивать вручную не нужно (если после установки программа сама не открылась — просто запустите её ещё раз; в версиях до 0.3.6 так бывает).

Если у вас версия 0.2.0 или старше — кнопка обновления в них не срабатывает (чёрное окно и ничего не происходит). Один раз скачайте CafedraSchedule.exe ниже и замените им старый файл — данные и настройки сохранятся, а дальше обновления пойдут сами.

Если ставите с нуля — скачайте CafedraSchedule.exe ниже и запустите двойным кликом. Python и git не нужны. Для чтения старых .doc файлов на компьютере должен быть установлен MS Word или LibreOffice."""


def release_notes_markdown(version: str) -> str:
    """Текст GitHub-релиза для версии — из той же записи, что видит человек в окне
    «Что нового», чтобы не писать одно и то же дважды. KeyError, если записи нет."""
    wanted = _parse_version(version)
    ordered = sorted(CHANGELOG, key=lambda e: _parse_version(e["version"]), reverse=True)
    for i, entry in enumerate(ordered):
        if _parse_version(entry["version"]) != wanted:
            continue
        prev = ordered[i + 1]["version"] if i + 1 < len(ordered) else None
        lines = [f"Что нового с v{prev}:" if prev else "Первая версия:", ""]
        for j, (title, items) in enumerate(entry["sections"]):
            if j > 0:
                lines += ["", f"{title}:", ""]
            lines += [f"- {it}" for it in items]
        return "\n".join(lines) + "\n\n" + _RELEASE_FOOTER + "\n"
    raise KeyError(f"В changelog.py нет записи для версии {version}")
