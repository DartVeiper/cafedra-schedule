def entries_for_display() -> list[dict]:
    """Записи новее → старее, с признаками installed (текущая версия) и
    unreleased (новее установленной — работа в процессе)."""
    current = _parse_version(APP_VERSION)
    out = []
    for e in sorted(CHANGELOG, key=lambda e: _parse_version(e["version"]), reverse=True):
        v = _parse_version(e["version"])
        out.append({**e, "installed": v == current, "unreleased": v > current})
    return out
